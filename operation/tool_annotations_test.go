// registeredTools enumerates every tool the server exposes, keyed by name.
func registeredTools(t *testing.T) map[string]mcp.Tool {
	t.Helper()
	s := server.NewMCPServer("forgejo-mcp", "test")
	operation.RegisterTool(s)
	registered := s.ListTools()
	tools := make(map[string]mcp.Tool, len(registered))
	for name, st := range registered {
		tools[name] = st.Tool
	}
	return tools
}

// classOf maps every golden tool name to its class and fails on duplicates.
// It also pins wantMutatingIdempotent to the mutating class: an entry that
// names no golden tool (stale after a rename or removal), names a non-mutating
// tool, or duplicates an earlier entry would otherwise be silently ignored by
// TestToolAnnotationValues, which only looks the list up per registered tool.
func classOf(t *testing.T) map[string]string {
	t.Helper()
	class := make(map[string]string, len(wantReadOnly)+len(wantMutating)+len(wantDestructive))
	add := func(names []string, c string) {
		for _, n := range names {
			if prev, ok := class[n]; ok {
				t.Errorf("tool %q appears in both %s and %s golden lists", n, prev, c)
				continue
			}
			class[n] = c
		}
	}
	add(wantReadOnly, "read-only")
	add(wantMutating, "mutating")
	add(wantDestructive, "destructive")

	seen := make(map[string]bool, len(wantMutatingIdempotent))
	for _, n := range wantMutatingIdempotent {
		if seen[n] {
			t.Errorf("tool %q appears more than once in wantMutatingIdempotent", n)
		}
		seen[n] = true
		c, ok := class[n]
		if !ok {
			t.Errorf("tool %q is in wantMutatingIdempotent but in no golden list", n)
			continue
		}
		if c != "mutating" {
			t.Errorf("tool %q is in wantMutatingIdempotent but classified %s; only mutating tools may be listed there", n, c)
		}
	}
	return class
}

func hint(t *testing.T, tool, field string, b *bool) bool {
	t.Helper()
	if b == nil {
		t.Fatalf("tool %s: %s hint is not set", tool, field)
	}
	return *b
}

func containsName(names []string, name string) bool {
	for _, n := range names {
		if n == name {
			return true
		}
	}
	return false
}

// TestToolAnnotationsGolden fails when a registered tool is missing from the
// golden lists, or a golden name is not registered — new tools must be
// classified before they ship.
func TestToolAnnotationsGolden(t *testing.T) {
	tools := registeredTools(t)
	class := classOf(t)

	for name := range tools {
		if _, ok := class[name]; !ok {
			t.Errorf("registered tool %q is not in any golden list; classify it per the \"Tool Annotations Are Required\" rubric in DEVELOPER.md, add the matching With*HintAnnotation calls, then add it to the golden lists here", name)
		}
	}
	for name := range class {
		if _, ok := tools[name]; !ok {
			t.Errorf("golden tool %q is classified but not registered", name)
		}
	}
}

// TestToolAnnotationValues checks that every tool carries the full set of
// hints with values matching its golden class.
func TestToolAnnotationValues(t *testing.T) {
	tools := registeredTools(t)
	class := classOf(t)

	for name, tool := range tools {
		a := tool.Annotations
		readOnly := hint(t, name, "readOnlyHint", a.ReadOnlyHint)
		destructive := hint(t, name, "destructiveHint", a.DestructiveHint)
		idempotent := hint(t, name, "idempotentHint", a.IdempotentHint)
		openWorld := hint(t, name, "openWorldHint", a.OpenWorldHint)

		if a.Title == "" {
			t.Errorf("tool %s: title annotation is empty", name)
		}
		// All tools talk to the single configured Forgejo instance.
		if openWorld {
			t.Errorf("tool %s: openWorldHint is true; every tool targets the configured instance", name)
		}

		switch class[name] {
		case "read-only":
			if !readOnly || destructive || !idempotent {
				t.Errorf("tool %s: read-only class wants readOnly=true, destructive=false, idempotent=true; got %t/%t/%t",
					name, readOnly, destructive, idempotent)
			}
		case "mutating":
			if readOnly || destructive {
				t.Errorf("tool %s: mutating class wants readOnly=false, destructive=false; got %t/%t",
					name, readOnly, destructive)
			}
			if wantIdem := containsName(wantMutatingIdempotent, name); idempotent != wantIdem {
				t.Errorf("tool %s: idempotentHint=%t but golden classification says %t", name, idempotent, wantIdem)
			}
		case "destructive":
			if readOnly || !destructive || idempotent {
				t.Errorf("tool %s: destructive class wants readOnly=false, destructive=true, idempotent=false; got %t/%t/%t",
					name, readOnly, destructive, idempotent)
			}
		default:
			t.Errorf("tool %s: not in any golden list", name)
		}
	}
}

// TestToolAnnotationPrefixes guards the naming convention: a tool whose name
// claims to be read-only (or mutating) must not contradict its hints.
func TestToolAnnotationPrefixes(t *testing.T) {
	tools := registeredTools(t)
	readOnlyPrefixes := []string{"list_", "get_", "search_", "download_", "check_"}
	mutatingPrefixes := []string{"create_", "delete_", "update_", "edit_", "add_", "remove_", "set_"}

	for name, tool := range tools {
		readOnly := hint(t, name, "readOnlyHint", tool.Annotations.ReadOnlyHint)
		for _, p := range readOnlyPrefixes {
			if strings.HasPrefix(name, p) && !readOnly {
				t.Errorf("tool %s is named like a read operation (%q prefix) but readOnlyHint is false", name, p)
			}
		}
		for _, p := range mutatingPrefixes {
			if strings.HasPrefix(name, p) && readOnly {
				t.Errorf("tool %s is named like a write operation (%q prefix) but readOnlyHint is true", name, p)
			}
		}
	}
}
